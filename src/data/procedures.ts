/**
 * Равномерно разпределение на точки по сфера (Fibonacci sphere), превърнато
 * в lat/lon. Така сферата се справя с произволен брой процедури без ръчно
 * позициониране на всеки етикет.
 */
function fibonacciLatLon(index: number, total: number): { lat: number; lon: number } {
  const goldenAngle = Math.PI * (3 - Math.sqrt(5))
  const y = 1 - (index / Math.max(total - 1, 1)) * 2 // 1 → -1
  const lat = Math.asin(Math.max(-1, Math.min(1, y))) * (180 / Math.PI)
  let lon = ((goldenAngle * index) * (180 / Math.PI)) % 360
  if (lon > 180) lon -= 360
  return { lat, lon }
}

// Позициите се разпределят само между видимите на сферата процедури, за да
// няма „дупки“ в равномерната мрежа от скритите.
const sphereSeeds = seeds.filter((s) => s.sphere !== false)

export const procedures: Procedure[] = seeds.map((seed) => {
  const sphereIndex = sphereSeeds.indexOf(seed)
  const onSphere = sphereIndex >= 0
  const { lat, lon } = onSphere
    ? fibonacciLatLon(sphereIndex, sphereSeeds.length)
    : { lat: 0, lon: 0 }
  return { title: seed.title, description: seed.description, category: seed.category, lat, lon, onSphere }
})

/** Само процедурите, които се показват като етикети върху 3D сферата. */
export const sphereProcedures: Procedure[] = procedures.filter((p) => p.onSphere)
